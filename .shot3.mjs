import { chromium } from "playwright";
const OUT=process.argv[2], BASE="http://localhost:5180";
const b=await chromium.launch();
const p=await b.newPage({viewport:{width:1500,height:1000},deviceScaleFactor:2});
const errs=[]; p.on("pageerror",e=>errs.push(e.message));
await p.goto(BASE+"/login",{waitUntil:"networkidle"});
await p.getByText("A. Assistant").click(); await p.waitForURL("**/dashboard");
await p.evaluate(()=>localStorage.setItem("tulasetu.onboarding.seen","1"));
await p.goto(BASE+"/reports/TS-DEMO-0001/profile",{waitUntil:"networkidle"});
await p.waitForTimeout(1200);
await p.screenshot({path:`${OUT}/90-step1.png`});
await p.getByRole("button",{name:/Continue to Metrology/i}).click();
await p.waitForTimeout(1400);
await p.screenshot({path:`${OUT}/91-step2.png`});
await p.getByRole("button",{name:/Continue to Construction/i}).click();
await p.waitForTimeout(1200);
await p.screenshot({path:`${OUT}/92-step3.png`});
console.log("errors:", errs.length?errs.join("; "):"none");
await b.close();
